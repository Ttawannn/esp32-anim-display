const size_t kPresetCount = sizeof(kPresets) / sizeof(kPresets[0]);

int findPreset(const char* id) {
  for (size_t i = 0; i < kPresetCount; i++) {
    if (strcmp(kPresets[i].id, id) == 0) return (int)i;
  }
  return -1;
}
