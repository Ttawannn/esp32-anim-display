// Shade characters as ordered patterns over the whole cell.
const SHADES: Record<string, (x: number, y: number) => boolean> = {
  '░': (x, y) => (x & 1) === 0 && (y & 1) === 0,
  '▒': (x, y) => ((x + y) & 1) === 0,
  '▓': (x, y) => !((x & 1) === 1 && (y & 1) === 1),
  '█': () => true,
};

function build(src: Record<string, string>, cellW: number, cellH: number): BitmapFont {
  const glyphs = new Map<string, Uint8Array>();
  for (const [ch, rows] of Object.entries(src)) {
    const g = new Uint8Array(cellW * cellH);
    rows.split(' ').forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') g[y * cellW + x] = 1;
    });
    glyphs.set(ch, g);
  }
  for (const [ch, lit] of Object.entries(SHADES)) {
    const g = new Uint8Array(cellW * cellH);
    for (let y = 0; y < cellH; y++) for (let x = 0; x < cellW; x++) if (lit(x, y)) g[y * cellW + x] = 1;
    glyphs.set(ch, g);
  }
  return { cellW, cellH, glyphs };
}

export const SMALL_FONT = build(FONT_3X5, 4, 6);
export const FONT = build(FONT_5X7, 6, 8);

// Lit pixels of a glyph, used to sort a character set from sparse to dense.
export function inkOf(g: Uint8Array): number {
  let n = 0;
  for (let i = 0; i < g.length; i++) n += g[i];
  return n;
}
