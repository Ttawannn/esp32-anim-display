// Bitmap fonts for ASCII art. Pure data, so the encode worker and the template tests can draw
// characters without a canvas. Each glyph is a cell-sized bitmap (1 = lit) with the letter in the
// top-left corner and the spacing column/row on the right/bottom. Shade characters fill the whole
// cell so neighbouring blocks join up.

export interface BitmapFont {
  cellW: number;
  cellH: number;
  glyphs: Map<string, Uint8Array>; // cellW * cellH, row by row
}

